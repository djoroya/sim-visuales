function coef(esp, T) {
  for (const [lo, hi, c] of SHOMATE[esp]) if (T >= lo && T <= hi) return c;
  throw new Error(`${esp}: T = ${T} K fuera del rango de Shomate`);
}
export function entalpia(esp, T) {   // J/mol, con la de formación
  const [A, B, C, D, E, Fc] = coef(esp, T), t = T / 1000;
  return 1000 * (A * t + B * t ** 2 / 2 + C * t ** 3 / 3 + D * t ** 4 / 4 - E / t + Fc);
}
export function entropia(esp, T) {
  const [A, B, C, D, E, , G] = coef(esp, T), t = T / 1000;
  return A * Math.log(t) + B * t + C * t ** 2 / 2 + D * t ** 3 / 3 - E / (2 * t ** 2) + G;
}
export const gibbs = (esp, T) => entalpia(esp, T) - T * entropia(esp, T);
